"""Writes the table of countries (fastapi_alcazaba/countries/_iso3166.py) from ISO 3166-1.

    python scripts/generate_countries.py
    python scripts/generate_countries.py --check

The data is Debian's iso-codes (`apt install iso-codes`), a maintained copy of ISO 3166 in
JSON. --check writes nothing: it fails if the committed table, or the ISO 3166-2 codes of
Spain's provinces and communities (fastapi_alcazaba/countries/spain/provinces.py), differ from
the data.
"""

import argparse
import gzip
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "fastapi_alcazaba" / "countries" / "_iso3166.py"
DEFAULT_DATA = Path("/usr/share/iso-codes/json")

HEADER = '''"""ISO 3166-1: the officially assigned codes.

Generated by scripts/generate_countries.py from iso-codes {version}: don't edit it by hand.
"""

# alpha-2, alpha-3, numeric, English short name, official name (or None).
COUNTRIES: tuple[tuple[str, str, str, str, str | None], ...] = (
'''


def _load(data: Path, name: str, key: str) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = json.loads((data / name).read_text(encoding="utf-8"))[key]
    return rows


def _version(data: Path) -> str:
    """iso-codes' version, from the Debian package's changelog when there is one."""
    changelog = Path("/usr/share/doc/iso-codes/changelog.Debian.gz")
    if data == DEFAULT_DATA and changelog.exists():
        first = gzip.decompress(changelog.read_bytes()).decode().split("\n", 1)[0]
        return first.split("(", 1)[1].split("-", 1)[0]  # iso-codes (4.16.0-1) unstable; ...
    return "(unknown version)"


def render(data: Path) -> str:
    rows = sorted(_load(data, "iso_3166-1.json", "3166-1"), key=lambda row: row["alpha_2"])
    lines = [HEADER.format(version=_version(data))]
    for row in rows:
        values = (
            row["alpha_2"],
            row["alpha_3"],
            row["numeric"],
            row["name"],
            row.get("official_name"),
        )
        lines.append(f"    {values!r},\n")
    lines.append(")\n")
    # Formatted as `ruff format` would, so that `make format` leaves it as it is.
    formatted = subprocess.run(  # noqa: S603  # our own interpreter and ruff, no shell
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(TABLE), "-"],
        input="".join(lines),
        capture_output=True,
        text=True,
        check=True,
    )
    return formatted.stdout


def check_spain(data: Path) -> list[str]:
    """The ISO 3166-2 code and parent of each province and community, against the data."""
    sys.path.insert(0, str(ROOT))
    from fastapi_alcazaba.countries.spain import COMMUNITIES, PROVINCES

    iso = {row["code"]: row for row in _load(data, "iso_3166-2.json", "3166-2")}
    problems = []
    for community in COMMUNITIES:
        if community.iso_code not in iso:
            problems.append(f"{community.name}: no {community.iso_code} in ISO 3166-2")
    for province in PROVINCES:
        row = iso.get(province.iso_code)
        if row is None:
            problems.append(f"{province.name}: no {province.iso_code} in ISO 3166-2")
            continue
        # Ceuta and Melilla are a province and a city at once: the city's code, with no parent.
        parent = row.get("parent", row["code"])
        if parent != province.community.iso_code:
            problems.append(f"{province.name}: in {parent}, not {province.community.iso_code}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="compare, don't write")
    parser.add_argument("--data", type=Path, default=DEFAULT_DATA, help="iso-codes' json folder")
    args = parser.parse_args()

    table = render(args.data)
    if not args.check:
        TABLE.write_text(table, encoding="utf-8")
        print(f"wrote {TABLE.relative_to(ROOT)}")
        return 0
    problems = check_spain(args.data)
    if TABLE.read_text(encoding="utf-8") != table:
        problems.append(f"{TABLE.relative_to(ROOT)} is out of date: run the script")
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
